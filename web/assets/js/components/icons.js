/**
 * Trả về SVG inline kích thước 16x16, stroke-width 1.5 theo chuẩn Lucide.
 * @param {string} name
 * @param {string} [className='w-4 h-4']
 * @returns {string}
 */
export function getIcon(name, className = 'w-4 h-4') {
  if (typeof name !== 'string') return '';
  const key = name.trim();
  if (!Object.prototype.hasOwnProperty.call(ICON_PATHS, key)) {
    return '';
  }

  const rawClass = typeof className === 'string' && className.trim() ? className.trim() : 'w-4 h-4';
  const safeClass = escapeHtml(rawClass);

  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 24 24" ` +
    `fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" ` +
    `stroke-linejoin="round" aria-hidden="true" class="${safeClass}">${ICON_PATHS[key]}</svg>`
  );
}
